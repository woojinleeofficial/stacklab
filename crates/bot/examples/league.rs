//! Bot league calibration (spec 7.3). Adjacent presets play `games` rounds each (sides
//! alternate, distinct seeds) on the real engine; ratings are fitted with the reference preset
//! fixed at 1500. Writes data/bots/calibration.toml with `--write`.
//!
//! cargo run --release -p stacklab-bot --example league -- [games_per_pair] [--write]

use stacklab_bot::league::{play_round, ratings, Game};
use stacklab_bot::presets;
use stacklab_engine::Ruleset;
use std::sync::mpsc::channel;
use std::sync::Arc;
use std::time::Instant;

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let games: u64 = args.get(1).and_then(|s| s.parse().ok()).unwrap_or(200);
    let write = args.iter().any(|a| a == "--write");
    let rs = Arc::new(Ruleset::tl_s2());
    let pf = presets();
    let n = pf.preset.len();
    let reference = pf
        .preset
        .iter()
        .position(|p| p.id == pf.reference)
        .expect("reference preset");
    let t0 = Instant::now();
    // pairs (k-1, k) in parallel threads
    let (tx, rx) = channel();
    let threads = std::thread::available_parallelism()
        .map(|x| x.get())
        .unwrap_or(4);
    let jobs: Vec<(usize, u64)> = (1..n)
        .flat_map(|k| (0..games).map(move |g| (k, g)))
        .collect();
    let jobs = Arc::new(std::sync::Mutex::new(jobs));
    for _ in 0..threads {
        let (tx, jobs, rs, pf) = (tx.clone(), jobs.clone(), rs.clone(), pf.clone());
        std::thread::spawn(move || loop {
            let Some((k, g)) = jobs.lock().unwrap().pop() else {
                break;
            };
            let (lo, hi) = (&pf.preset[k - 1], &pf.preset[k]);
            let seed = 1_000_003 * k as u64 + g * 7919 + 11;
            // alternate sides
            let (a, b, hi_side) = if g % 2 == 0 { (lo, hi, 1) } else { (hi, lo, 0) };
            let o = play_round(a, b, &rs, seed);
            tx.send((k, o.winner == hi_side, o)).unwrap();
        });
    }
    drop(tx);
    let mut per_pair = vec![(0u32, 0u32, 0u64, 0u32); n];
    let mut record: Vec<Game> = Vec::new();
    for (k, hi_won, o) in rx {
        let e = &mut per_pair[k];
        e.0 += hi_won as u32;
        e.1 += 1;
        e.2 += o.frames;
        e.3 += o.capped as u32;
        record.push((k, k - 1, if hi_won { 1.0 } else { 0.0 }));
    }
    let r = ratings(n, reference, &record);
    println!(
        "bot league: {games} rounds per adjacent pair, reference {} = 1500, {:.0}s",
        pf.reference,
        t0.elapsed().as_secs_f64()
    );
    println!("preset  pps  depth beam mistake  rating   ±RD    vs lower (win%)  avg round  capped");
    let mut monotone = true;
    for (i, p) in pf.preset.iter().enumerate() {
        let vs = if i == 0 {
            "-".to_string()
        } else {
            let e = per_pair[i];
            format!(
                "{}/{} ({:.0}%)",
                e.0,
                e.1,
                100.0 * e.0 as f64 / e.1.max(1) as f64
            )
        };
        let avg = if i == 0 {
            0.0
        } else {
            per_pair[i].2 as f64 / per_pair[i].1.max(1) as f64 / 60.0
        };
        if i > 0 && r[i].rating <= r[i - 1].rating {
            monotone = false;
        }
        println!(
            "{:6} {:4.1} {:5} {:4} {:6.1}%  {:7.0} {:5.0}    {:16} {:6.0}s   {}",
            p.id,
            p.pps_milli as f64 / 1000.0,
            p.depth,
            p.beam,
            p.mistake_pm as f64 / 10.0,
            r[i].rating,
            r[i].rd,
            vs,
            avg,
            if i == 0 { 0 } else { per_pair[i].3 }
        );
    }
    println!("monotone with preset strength: {monotone}");
    if write {
        let mut t = String::from("# Generated by `cargo run --release -p stacklab-bot --example league -- <games> --write`.\n# Bot ratings on the app's Glicko-2 scale (reference preset = 1500). Do not edit by hand.\n");
        t += &format!("calibration_version = 1\ngames_per_pair = {games}\nreference = {:?}\nmonotone = {monotone}\n", pf.reference);
        for (i, p) in pf.preset.iter().enumerate() {
            t += &format!(
                "\n[[bot]]\nid = {:?}\nrating = {:.1}\nrd = {:.1}\n",
                p.id, r[i].rating, r[i].rd
            );
        }
        std::fs::write("data/bots/calibration.toml", t).expect("write calibration");
        println!("wrote data/bots/calibration.toml");
    }
}
