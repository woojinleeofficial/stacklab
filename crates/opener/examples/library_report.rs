//! STEP 4 report: per opener, branch validity and first-bag coverage (exhaustive for memorized
//! openers, sampled for templates).
//! cargo run --release -p stacklab-opener --example library_report

use stacklab_engine::{MoveRules, Ruleset};
use stacklab_opener::feasibility::{branch_valid, coverage};
use stacklab_opener::library::{Kind, Library};
use std::time::Instant;

fn main() {
    let write = std::env::args().any(|a| a == "--write");
    let rules = MoveRules::from_ruleset(&Ruleset::tl_s2());
    let lib = Library::bundled();
    let mut toml = String::from("# Generated by `cargo run --release -p stacklab-opener --example library_report -- --write`.\n# Coverage of each opener version (spec 8.2 OpenerCoverage). Do not edit by hand.\n");
    for def in &lib.openers {
        println!(
            "== {} ({}) v{} — {:?}, source: {}",
            def.name, def.id, def.version, def.kind, def.source
        );
        for b in &def.branches {
            println!(
                "  branch {:<24} pieces {} reserve {:?} finisher {:?}: {}",
                b.id,
                b.pieces.len(),
                b.reserve,
                b.finisher,
                match branch_valid(b, &rules) {
                    Ok(()) => "OK".to_string(),
                    Err(e) => e,
                }
            );
        }
        let step = if def.kind == Kind::Memorized {
            1
        } else if def.id == "pc-first" {
            120
        } else {
            40
        };
        let t = Instant::now();
        let c = coverage(def, &rules, step, 6);
        println!(
            "  coverage [{}]: full-sequence {}/{} ({:.1}%), visible-info {}/{} ({:.1}%, 95% CI {:.1}–{:.1}%) guaranteed={} ({:.1}s)",
            c.scope, c.full, c.total, 100.0 * c.full as f64 / c.total as f64, c.visible, c.total, 100.0 * c.rate(), 100.0 * c.ci95.0, 100.0 * c.ci95.1, c.is_guaranteed(), t.elapsed().as_secs_f64()
        );
        toml += &format!(
            "\n[{}]\nversion = {}\nscope = {:?}\nexhaustive = {}\ntotal = {}\nfull = {}\nvisible = {}\nci_low = {:.4}\nci_high = {:.4}\n",
            def.id, def.version, c.scope, c.exhaustive, c.total, c.full, c.visible, c.ci95.0, c.ci95.1
        );
    }
    if write {
        std::fs::write("data/openers/coverage.toml", toml).expect("write coverage");
        println!("wrote data/openers/coverage.toml");
    }
}
